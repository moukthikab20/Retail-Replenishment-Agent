def product_retail_price(product: dict[str, Any]) -> float:
    """Deterministic shelf price by SKU (separate from unit cost)."""
    sku_num = int(str(product["sku"]).split("-")[-1])
    markup = _CATEGORY_RETAIL_MARKUP.get(str(product.get("category", "")), 1.40)
    tweak = 1.0 + ((sku_num * 17) % 11) * 0.01
    return round(float(product["unit_cost"]) * markup * tweak, 2)
